// ---------- helpers ----------
const para = (text, opts = {}) => new Paragraph({
  spacing: { after: 100, line: 288 },
  alignment: opts.align || AlignmentType.JUSTIFIED,
  indent: opts.indent === false ? undefined : { firstLine: 567 },
  keepNext: opts.keepNext,
  children: Array.isArray(text) ? text : [new TextRun({ text, ...(opts.run || {}) })],
});

const h1 = (text) => new Paragraph({
  heading: HeadingLevel.HEADING_1,
  pageBreakBefore: true,
  spacing: { before: 0, after: 200 },
  border: { bottom: { style: BorderStyle.SINGLE, size: 6, color: RED, space: 4 } },
  children: [new TextRun({ text })],
});

const bullet = (text) => new Paragraph({
  numbering: { reference: 'bullets', level: 0 },
  spacing: { after: 50, line: 276 },
  alignment: AlignmentType.JUSTIFIED,
  children: [new TextRun(text)],
});

const numbered = (text, ref) => new Paragraph({
  numbering: { reference: ref, level: 0 },
  spacing: { after: 50, line: 276 },
  alignment: AlignmentType.JUSTIFIED,
  children: [new TextRun(text)],
});

const border = { style: BorderStyle.SINGLE, size: 4, color: 'BFBFBF' };
const borders = { top: border, bottom: border, left: border, right: border };

const table = (widths, header, rows, opts = {}) => new Table({
  width: { size: widths.reduce((a, b) => a + b, 0), type: WidthType.DXA },
  columnWidths: widths,
  rows: [
    new TableRow({
      tableHeader: true,
      children: header.map((t, i) => new TableCell({
        width: { size: widths[i], type: WidthType.DXA },
        borders,
        shading: { type: ShadingType.CLEAR, color: 'auto', fill: RED },
        margins: { top: 70, bottom: 70, left: 110, right: 110 },
        children: [new Paragraph({ children: [new TextRun({ text: t, bold: true, color: 'FFFFFF', size: opts.size || 22 })] })],
      })),
    }),
    ...rows.map((r, ri) => new TableRow({
      cantSplit: true,
      children: r.map((t, i) => new TableCell({
        width: { size: widths[i], type: WidthType.DXA },
        borders,
        shading: ri % 2 ? { type: ShadingType.CLEAR, color: 'auto', fill: 'F5EFEA' } : undefined,
        margins: { top: 50, bottom: 50, left: 110, right: 110 },
        children: [new Paragraph({ children: [new TextRun({ text: t, bold: i === 0, size: opts.size || 22 })] })],
      })),
    })),
  ],
});

const spacer = () => new Paragraph({ spacing: { after: 120 }, children: [] });

// ---------- articles ----------
// Статья: { n, t, b: [строки | {list: [...]} | {ol: [...]}], pen }
const all = [];
let olCounter = 0;
const numberingConfigs = [];

const renderArticle = (a) => {
  const out = [new Paragraph({
    keepNext: true,
    spacing: { before: 180, after: 70 },
    children: [
      new TextRun({ text: `Статья ${a.n}. `, bold: true, color: RED }),
      new TextRun({ text: a.t, bold: true }),
    ],
  })];
  (a.b || []).forEach((item) => {
    if (typeof item === 'string') out.push(para(item));
    else if (item.list) item.list.forEach((t) => out.push(bullet(t)));
    else if (item.ol) {
      const ref = `ol${++olCounter}`;
      numberingConfigs.push({ reference: ref, levels: [{ level: 0, format: LevelFormat.DECIMAL, text: '%1)', alignment: AlignmentType.LEFT, style: { paragraph: { indent: { left: 720, hanging: 360 } } } }] });
      item.ol.forEach((t) => out.push(numbered(t, ref)));
    }
  });
  if (a.pen) {
    out.push(new Paragraph({
      spacing: { before: 40, after: 140 },
      indent: { firstLine: 567 },
      alignment: AlignmentType.JUSTIFIED,
      children: [
        new TextRun({ text: 'Мера взыскания: ', bold: true, italics: true, color: RED }),
        new TextRun({ text: a.pen, italics: true }),
      ],
    }));
  }
  return out;
};

const chapters = [];
const chapter = (title, intro, articles) => {
  chapters.push(title);
  const out = [h1(title)];
  (intro || []).forEach((t) => out.push(para(t)));
  articles.forEach((a) => { all.push({ ...a, ch: title }); out.push(...renderArticle(a)); });
  return out;
};

