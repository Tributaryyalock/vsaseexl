const para = (text, opts = {}) => new Paragraph({
  spacing: { after: 90, line: 288 },
  alignment: opts.align || AlignmentType.JUSTIFIED,
  indent: opts.indent === false ? undefined : { firstLine: 567 },
  keepNext: opts.keepNext,
  children: Array.isArray(text) ? text : [new TextRun({ text, ...(opts.run || {}) })],
});

const sectionTitle = (text, sub) => [
  new Paragraph({ pageBreakBefore: true, alignment: AlignmentType.CENTER, spacing: { before: 2400, after: 200 },
    children: [new TextRun({ text: '★', size: 56, color: RED })] }),
  new Paragraph({ alignment: AlignmentType.CENTER, spacing: { after: 160 },
    children: [new TextRun({ text, bold: true, size: 40, color: RED, characterSpacing: 60 })] }),
  new Paragraph({ alignment: AlignmentType.CENTER, spacing: { after: 200 },
    children: [new TextRun({ text: sub, size: 30 })] }),
];

const h1 = (text) => new Paragraph({
  heading: HeadingLevel.HEADING_1,
  pageBreakBefore: true,
  spacing: { before: 0, after: 200 },
  border: { bottom: { style: BorderStyle.SINGLE, size: 6, color: RED, space: 4 } },
  children: [new TextRun({ text })],
});

const bullet = (text) => new Paragraph({
  numbering: { reference: 'bullets', level: 0 },
  spacing: { after: 40, line: 276 },
  alignment: AlignmentType.JUSTIFIED,
  children: [new TextRun(text)],
});

const border = { style: BorderStyle.SINGLE, size: 4, color: 'BFBFBF' };
const borders = { top: border, bottom: border, left: border, right: border };
const table = (widths, header, rows, opts = {}) => new Table({
  width: { size: widths.reduce((a, b) => a + b, 0), type: WidthType.DXA },
  columnWidths: widths,
  rows: [
    new TableRow({
      tableHeader: true,
      children: header.map((t, i) => new TableCell({
        width: { size: widths[i], type: WidthType.DXA }, borders,
        shading: { type: ShadingType.CLEAR, color: 'auto', fill: RED },
        margins: { top: 60, bottom: 60, left: 100, right: 100 },
        children: [new Paragraph({ children: [new TextRun({ text: t, bold: true, color: 'FFFFFF', size: opts.size || 21 })] })],
      })),
    }),
    ...rows.map((r, ri) => new TableRow({
      cantSplit: true,
      children: r.map((t, i) => new TableCell({
        width: { size: widths[i], type: WidthType.DXA }, borders,
        shading: ri % 2 ? { type: ShadingType.CLEAR, color: 'auto', fill: 'F5EFEA' } : undefined,
        margins: { top: 45, bottom: 45, left: 100, right: 100 },
        children: [new Paragraph({ children: [new TextRun({ text: t, bold: i === 0 && opts.boldFirst !== false, size: opts.size || 21, color: opts.starCol === i ? RED : undefined })] })],
      })),
    })),
  ],
});
const spacer = () => new Paragraph({ spacing: { after: 100 }, children: [] });

const stars = (n) => '★'.repeat(n) + '☆'.repeat(6 - n);

// ===================================================================
