let artNo = 0;
const index = []; // для сводной таблицы
const chapterTitles = [];

// Статья общей части: G(title, [строки | {list:[...]}])
const G = (title, body, note) => ({ kind: 'g', title, body, note });
// Статья особенной части: A(title, ref, [[текст, наказание, розыск], ...], note)
const A = (title, ref, parts, note) => ({ kind: 'a', title, ref, parts, note });

const renderArticle = (a, chapter) => {
  artNo += 1;
  const out = [new Paragraph({
    keepNext: true,
    spacing: { before: 200, after: a.ref ? 20 : 70 },
    children: [
      new TextRun({ text: `Статья ${artNo}. `, bold: true, color: RED }),
      new TextRun({ text: a.title, bold: true }),
    ],
  })];
  if (a.ref) {
    out.push(new Paragraph({ keepNext: true, spacing: { after: 70 },
      children: [new TextRun({ text: `По мотивам ст. ${a.ref} УК РСФСР`, italics: true, size: 19, color: GREY })] }));
  }
  if (a.kind === 'g') {
    a.body.forEach((item) => {
      if (typeof item === 'string') out.push(para(item));
      else item.list.forEach((t) => out.push(bullet(t)));
    });
  } else {
    const multi = a.parts.length > 1;
    a.parts.forEach(([text, pen, w], i) => {
      out.push(para(multi ? [new TextRun({ text: `${i + 1}. `, bold: true }), new TextRun(text)] : text, { keepNext: true }));
      out.push(new Paragraph({
        spacing: { after: 110 },
        indent: { firstLine: 567 },
        alignment: AlignmentType.LEFT,
        children: [
          new TextRun({ text: 'Наказание: ', bold: true, italics: true, color: RED }),
          new TextRun({ text: pen + '.', italics: true }),
          new TextRun({ text: '   Розыск: ', bold: true, size: 20, color: GREY }),
          new TextRun({ text: stars(w), size: 20, color: RED }),
        ],
      }));
    });
    index.push([String(artNo), a.title, stars(Math.max(...a.parts.map((p) => p[2])))]);
  }
  if (a.note) {
    out.push(new Paragraph({ spacing: { after: 110 }, indent: { firstLine: 567 }, alignment: AlignmentType.JUSTIFIED,
      children: [new TextRun({ text: 'Примечание. ', bold: true, size: 21 }), new TextRun({ text: a.note, size: 21 })] }));
  }
  return out;
};

const chapter = (title, intro, articles) => {
  chapterTitles.push(title);
  const out = [h1(title)];
  (intro || []).forEach((t) => out.push(para(t)));
  articles.forEach((a) => out.push(...renderArticle(a, title)));
  return out;
};

