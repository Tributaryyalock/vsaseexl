// Глава с автонумерацией пунктов «N.k»
const chapterOf = (n, title, items) => {
  let k = 0;
  return {
    title: `Глава ${n}. ${title}`,
    blocks: items.map((it) => {
      if (typeof it === 'string') { k += 1; return [`${n}.${k}`, it]; }
      if (it && it.p) return it.p;
      return it;
    }),
  };
};

